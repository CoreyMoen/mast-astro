#!/usr/bin/env node
/**
 * mast-astro CLI.
 *
 *   npx mast-astro init [--force] [--no-skills]
 *
 * Writes src/styles/theme.css (every customizable token at Mast's
 * defaults; never overwritten without --force) and installs the
 * mast-build agent skill into .agents/skills/ with a .claude/skills/
 * link (refreshed on every run, so re-run init after upgrading).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { version } = JSON.parse(
  fs.readFileSync(path.join(pkgDir, "package.json"), "utf8"),
);
const cwd = process.cwd();
const [command, ...flags] = process.argv.slice(2);

if (command !== "init") {
  console.log(`mast-astro ${version}

Usage: npx mast-astro init [--force] [--no-skills]

  Writes src/styles/theme.css with every customizable Mast token, and
  installs the mast-build agent skill for Claude Code and other agents.

  --force      overwrite an existing src/styles/theme.css
  --no-skills  skip the agent skill`);
  process.exit(command && command !== "help" && command !== "--help" ? 1 : 0);
}

if (!fs.existsSync(path.join(cwd, "package.json"))) {
  console.error("Run this from your project root (no package.json here).");
  process.exit(1);
}

const rel = (p) => path.relative(cwd, p);

// ---- Theme: the editable top of tokens.css, unlayered ----
const themePath = path.join(cwd, "src", "styles", "theme.css");
if (fs.existsSync(themePath) && !flags.includes("--force")) {
  console.log(
    `✓ ${rel(themePath)} already exists; left untouched (--force to replace)`,
  );
} else {
  const tokens = fs.readFileSync(
    path.join(pkgDir, "src/styles/tokens.css"),
    "utf8",
  );
  const start = tokens.indexOf(":root {") + ":root {".length;
  const computed = tokens.indexOf("Computed fluid values");
  const end = tokens.lastIndexOf("  /*", computed);
  if (start < ":root {".length || computed < 0 || end < start) {
    console.error("Couldn't read mast-astro's tokens.css; please report this.");
    process.exit(1);
  }
  // Custom properties only: an unlayered `color-scheme` on :root would
  // beat the .u-mode-light / .u-mode-dark classes the theme toggle sets.
  const body = tokens
    .slice(start, end)
    .replace(/^\s*color-scheme:.*\n\n?/m, "\n")
    .trimEnd();
  const theme = `/*
 * Your Mast theme, generated by \`npx mast-astro init\` (mast-astro ${version}).
 *
 * Every token Mast lets you customize, at Mast's defaults. Edit values in
 * place; delete a line to fall back to Mast's default. This file is
 * yours: upgrading mast-astro never changes it, and tokens added in later
 * versions take their defaults from the package.
 *
 * Fluid sizes are *-min / *-max pairs in rem; Mast computes the clamp()
 * values from them. Docs: node_modules/mast-astro/docs/theming.md
 *
 * These rules are unlayered, so they beat Mast's tokens whatever the
 * import order. The @layer line fixes Mast's layer order in case this
 * file loads first; put your own component CSS in \`@layer components\`.
 */

@layer tokens, base, layout, typography, components, styleguide, utilities;

:root {${body}
}
`;
  fs.mkdirSync(path.dirname(themePath), { recursive: true });
  fs.writeFileSync(themePath, theme);
  console.log(`✓ wrote ${rel(themePath)}`);
}

// ---- Agent skill: .agents/skills (cross-agent) + .claude/skills link ----
if (!flags.includes("--no-skills")) {
  const name = "mast-build";
  const from = path.join(pkgDir, ".agents", "skills", name);
  const to = path.join(cwd, ".agents", "skills", name);
  fs.rmSync(to, { recursive: true, force: true });
  fs.cpSync(from, to, {
    recursive: true,
    filter: (src) => path.basename(src) !== "evals",
  });
  console.log(`✓ installed the ${name} skill in ${rel(to)}`);

  const link = path.join(cwd, ".claude", "skills", name);
  let linkStat = null;
  try {
    linkStat = fs.lstatSync(link);
  } catch {}
  if (linkStat?.isSymbolicLink()) {
    // Already linked; the copy above refreshed its target.
  } else {
    fs.rmSync(link, { recursive: true, force: true });
    fs.mkdirSync(path.dirname(link), { recursive: true });
    try {
      fs.symlinkSync(path.relative(path.dirname(link), to), link, "dir");
      console.log(`✓ linked ${rel(link)} for Claude Code`);
    } catch {
      // Symlinks can need extra permissions on Windows; copy instead.
      fs.cpSync(to, link, { recursive: true });
      console.log(`✓ copied the skill to ${rel(link)} for Claude Code`);
    }
  }
}

console.log(`
Next: import Mast and your theme once, in your layout:

  ---
  import { BaseLayout } from "mast-astro"; // loads mast-astro/styles
  import "../styles/theme.css";
  ---
  <BaseLayout title="Home">…</BaseLayout>

Or, with your own layout: import "mast-astro/styles"; then the theme.
Guide: node_modules/mast-astro/docs/getting-started.md`);
